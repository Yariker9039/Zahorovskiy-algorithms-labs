# Задача 2. Підсумки за місяцями.
# Підсумки лежать у масиві фіксованого розміру (12 комірок).
# Номер місяця слугує індексом: місяць 1 -> комірка 0, місяць 12 -> комірка 11.

operations = [
    (1, 1500.0),
    (3, 200.0),
    (3, 350.5),
    (7, 1200.0),
    (12, 99.9),
    (1, 300.0),
    (7, -200.0),
]

totals = [0.0] * 12  # розмір не змінюється протягом усієї програми

for month, amount in operations:
    totals[month - 1] += amount  # індекс = номер місяця, перебору немає

for m in range(12):
    print(f"Місяць {m + 1:2}: {totals[m]:.2f}")
