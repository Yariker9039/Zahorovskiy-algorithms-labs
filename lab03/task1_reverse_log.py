# Задача 1. Журнал у зворотному порядку.
# Рядки складаємо додаванням у кінець, порядок змінюємо вже після того,
# як усе зібрано. Вставок на початок немає.

lines = [
    "Запуск системи",
    "Користувач увійшов",
    "Відкрито файл звіту",
    "Збережено зміни",
    "Користувач вийшов",
]

log = []
for line in lines:
    log.append(line)  # додавання в кінець

# Виводимо в зворотному порядку: йдемо по індексах від кінця до початку
for i in range(len(log) - 1, -1, -1):
    print(log[i])
